export const iconNames = Object.keys(iconRegistry).sort();

export function iconByName(name: string | null | undefined, fallback: LucideIcon = Briefcase): LucideIcon {
  if (name && iconRegistry[name]) return iconRegistry[name];
  return fallback;
}

export function iconNameOf(icon: LucideIcon | undefined): string {
  if (!icon) return "Briefcase";
  const entry = Object.entries(iconRegistry).find(([, value]) => value === icon);
  return entry ? entry[0] : "Briefcase";
}
